# Let moles of SO4^2- be x.
# Let moles of NO3^- be y.

# Total mass of Oxygen = 272 g:
# Each SO4^2- has 4 Oxygen atoms.
# Each NO3^- has 3 Oxygen atoms.
# Total moles of Oxygen atoms = 4x + 3y.
# Mass of Oxygen = (4x + 3y) * 16 = 272 g.
# 4x + 3y = 272 / 16 = 17 mol O atoms.

# Electrons in each ion:
# For SO4^2-:
# S (Z=16), 4 O (4*8=32), charge -2 (+2 e) => 16 + 32 + 2 = 50 electrons per ion.
# Moles of electrons in SO4^2- = 50x.

# For NO3^-:
# N (Z=7), 3 O (3*8=24), charge -1 (+1 e) => 7 + 24 + 1 = 32 electrons per ion.
# Moles of electrons in NO3^- = 32y.

# Difference in electrons:
# Total electrons in SO4^2- is 2.408e24 more than in NO3^-:
# Difference in moles of electrons = 2.408e24 / 6.02e23 = 4 mol electrons.
# 50x - 32y = 4.

# System of two linear equations:
# 1) 4x + 3y = 17
# 2) 50x - 32y = 4

# Multiply (1) by 32 and (2) by 3:
# 128x + 96y = 544
# 150x - 96y = 12
# Add them:
# 278x = 556 => x = 556 / 278 = 2 mol SO4^2-!
# From (1): 4(2) + 3y = 17 => 8 + 3y = 17 => 3y = 9 => y = 3 mol NO3^-!

# Total moles of ions = x + y = 2 + 3 = 5 mol.
# Mole percentage of NO3^-:
# Mole % = (y / (x + y)) * 100 = (3 / 5) * 100 = 60%!

# Options:
# 1) 30
# 2) 40
# 3) 70
# 4) 60
# Option 4 is 60!
print("P5-Q15: NO3^- mole % = 60% -> Option 4")
