def new_block(new):
    old = MAP[new]
    b = blocks[old]
    b = re.sub(r"#qbox\(\d+,", f"#qbox({new},", b, count=1)
    b = re.sub(r'(#qbox\(\d+, "[^"]*", ")[^"]*(")', r"\g<1>" + ORIG[new] + r"\g<2>", b, count=1)
    sec = SEC_OF[new]
    concept = (f"  *تحلیل مفهومی (در حد کتاب دهم):* {GOAL[new]} راهبرد این بخش: {METHOD[sec]}\n  \n  *گام‌های حل تشریحی (زنجیره کسر تبدیل):*")
    assert "*گام‌های حل تشریحی:*" in b
    b = b.replace("*گام‌های حل تشریحی:*", concept, 1)
    keym = re.search(r', "([۱۲۳۴])", \[', b)
    key = {"۱":"۱","۲":"۲","۳":"۳","۴":"۴"}[keym.group(1)] if keym else "درست"
    close = (f"\n  \n  *راستی‌آزمایی:* واحد پاسخ با خواسته سوال یکی است و مقدار به‌دست‌آمده دقیقاً روی گزینه {key} می‌نشیند؛ "
             f"خطای رایج این تیپ تست، جابه‌جا گرفتن صورت و مخرج کسر تبدیل یا جا انداختن ضریب تعداد اتم در فرمول است.\n])")
    assert b.rstrip().endswith("])")
    b = b.rstrip()[:-2] + close
    return b

