# Reference: 78_34 Se has Z = 34, A = 78, N = 78 - 34 = 44.
# For a species to be an isotope of Se, its neutral atom must have Z = 34 (same atomic number, different or same mass number).

# Option 1: A^2- has only 8 completely filled subshells, and N - e = 4.
# Subshell filling order: 1s, 2s, 2p, 3s, 3p, 4s, 3d, 4p.
# Exactly 8 filled subshells: 1s^2, 2s^2, 2p^6, 3s^2, 3p^6, 4s^2, 3d^10, 4p^6 = 36 electrons!
# Since A^2- has 36 electrons => Z_A = 36 - 2 = 34 (Selenium!).
# N - e = 4 => N - 36 = 4 => N = 40.
# Since Z = 34 and N = 40 (different from 44), it IS an isotope of Se!

# Option 2: Atom G with A = 79.
# Difference between subatomic particles inside and outside nucleus = 45.
# Inside nucleus: p + N = A = 79.
# Outside nucleus: e = p.
# Difference = (p + N) - e = A - p = N = 45!
# If N = 45, then p = A - N = 79 - 45 = 34.
# Since p = 34, Z = 34! It IS an isotope of Se!

# Option 3: B^2+ has 36 electrons.
# If B^2+ has 36 electrons => p = 36 + 2 = 38 (Strontium, not Selenium!).
# Z = 38 != 34! So it CANNOT be an isotope of Selenium!
# Let's check: difference between charged particles and neutral particles:
# Charged particles = p + e = 38 + 36 = 74.
# Neutral particles = N.
# |74 - N| = 26 => N = 48 or 100.
# Either way, Z = 38, so it is NOT an isotope of Se!
# Therefore, Option 3 is NOT an isotope of Se!

# Option 4: Element in same group as most abundant nonmetal of Earth (Oxygen -> Group 16)
# and same period as most abundant metal of Earth (Iron, 4th period, or Aluminum/Iron: Earth's crust: Al, Earth as a whole: Fe, both in period 3 or 4; Se is Group 16, Period 4!).
# So Group 16, Period 4 is Selenium (Z = 34). With N = 46, it is an isotope of Se!

