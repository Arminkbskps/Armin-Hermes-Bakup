# Each molecule has (1 + n) atoms.
# Total atoms = 15.05e22 atoms.
# Moles of atoms = 15.05e22 / 6.02e23 = 15.05 / 60.2 = 0.25 mol atoms.
# Moles of XeFn molecules = (moles of atoms) / (1 + n) = 0.25 / (1 + n).
# Mass of XeFn = 10.35 g.
# Molar mass M = mass / moles = 10.35 / (0.25 / (1 + n)) = 10.35 * 4 * (1 + n) = 41.4 * (1 + n).
# So: 131 + 19*n = 41.4 + 41.4*n
# 131 - 41.4 = (41.4 - 19) * n
# 89.6 = 22.4 * n
# n = 89.6 / 22.4 = 4!
# Thus, n = 4, and the compound is XeF4!
# Molar mass of XeF4 = 131 + 4*19 = 131 + 76 = 207 g/mol.
# Mass of F in 1 mole of XeF4 = 4 * 19 = 76 g.
# In what mass of XeF4 is there 26.6 g of F?
# Mass of XeF4 = 26.6 * (207 / 76) = 26.6 * (2.723684) = 72.45 g!
# (Check: 26.6 / 76 = 0.35 mol of XeF4; 0.35 * 207 = 72.45 g!)
# So n = 4 and mass = 72.45 g.
