# Identifying the isotopes of Hydrogen:
# In hydrogen, Z = 1 always (p = 1, e = 1 for neutral atom).
# Isotope A: subatomic particles are all equal (p = e = n):
# Since p = 1, e = 1 => n = 1.
# Mass number A = p + n = 1 + 1 = 2 (Deuterium, 2H).
# Initial mass of A = 4 g.
# Moles of A = 4 / 2 = 2 mol 2H.
# (Stable isotope, does not decay).

# Isotope B: "بیشترین پایداری را بین ایزوتوپ‌های ساختگی آن دارد"
# Synthetic isotopes of Hydrogen: 4H, 5H, 6H, 7H.
# 4H is the most stable among synthetic isotopes (or 3H is natural radioactive).
# Notice: problem says half-life of B is 9e-22 s.
# 4H has half-life around 1e-22 to 9e-22 s.
# Mass number of B = 4 (4H, mass = 4 g/mol).
# Initial mass of B = 10 g.
# Initial moles of B = 10 / 4 = 2.5 mol.

# Isotope C: "دارای ۵ ذره زیراتمی بدون بار است"
# Uncharged subatomic particles = neutrons = 5.
# Mass number = p + n = 1 + 5 = 6 (6H, mass = 6 g/mol).
# Initial mass of C = 6 g.
# Initial moles of C = 6 / 6 = 1 mol.

# Time elapsed t = 9e-22 s.
# For B: T_1/2 = 9e-22 s => n = 1 half-life.
# Remaining mass of B = 10 / 2 = 5 g.
# Remaining moles of B = 2.5 / 2 = 1.25 mol.

# For C: T_1/2 = 3e-22 s => n = (9e-22) / (3e-22) = 3 half-lives.
# Remaining mass of C = 6 / 2^3 = 6 / 8 = 0.75 g.
# Remaining moles of C = 1 / 8 = 0.125 mol.

# For A: stable => remaining mass = 4 g, moles = 2 mol.

# Initial state:
# Total initial moles = n_A + n_B + n_C = 2 + 2.5 + 1 = 5.5 mol.
# Initial abundance (percent of moles) of B:
# %B_initial = (2.5 / 5.5) * 100 = 45.45%.

# Final state:
# Total final moles = 2 + 1.25 + 0.125 = 3.375 mol.
# Final abundance of B:
# %B_final = (1.25 / 3.375) * 100 = 37.037%.
# Decrease in percent abundance of B:
# %B_initial - %B_final = 45.45% - 37.04% = 8.41% ≈ 8%!

# Now for mass percentage of A:
# Initial total mass = 4 + 10 + 6 = 20 g.
# Initial mass % of A = (4 / 20) * 100 = 20%.

# Final total mass = 4 + 5 + 0.75 = 9.75 g.
# Final mass % of A = (4 / 9.75) * 100 = 41.025%.
# Increase in mass % of A = 41.025% - 20% = 21.025% ≈ 21%!

# Looking at options:
# 1) 21 - 8
# 2) 24 - 8
# 3) 21 - 10
# 4) 24 - 10
# Decrease of B = 8%, Increase of A = 21%!
# Option 1 matches EXACTLY: 21 and 8!
