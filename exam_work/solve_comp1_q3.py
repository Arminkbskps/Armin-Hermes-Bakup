# Mixture of SO2 and C2 H5 OH.
# Total mass = 101 g.
# Molar masses:
# M(SO2) = 32 + 2*16 = 64 g/mol.
# M(C2 H5 OH) = 2*12 + 6*1 + 16 = 24 + 6 + 16 = 46 g/mol.
# Higher molar mass compound = SO2 (64 g/mol).

# Number of Carbon atoms = 1.806e24.
# Moles of Carbon atoms = 1.806e24 / 6.02e23 = 3 mol C.
# Carbon comes ONLY from ethanol (C2 H5 OH), which has 2 C atoms per molecule.
# Moles of C2 H5 OH = 3 / 2 = 1.5 mol!

# Mass of C2 H5 OH = 1.5 mol * 46 g/mol = 69 g.
# Mass of SO2 = Total mass - Mass of ethanol = 101 - 69 = 32 g!
# Moles of SO2 = 32 / 64 = 0.5 mol!

# Total moles of compounds = n(SO2) + n(ethanol) = 0.5 + 1.5 = 2.0 mol.

# Mole percentage of the compound with higher molar mass (SO2):
# Mole % of SO2 = (0.5 / 2.0) * 100 = 25%!

# Total moles of Oxygen atoms:
# From SO2 (0.5 mol, 2 O per molecule): 0.5 * 2 = 1.0 mol O.
# From C2 H5 OH (1.5 mol, 1 O per molecule): 1.5 * 1 = 1.5 mol O.
# Total moles of O atoms = 1.0 + 1.5 = 2.5 mol O!

