# In CO2: 1 Carbon atom + 2 Oxygen atoms.
# Carbon isotopes: 12C and 13C.
# Ratio of light to heavy carbon = N(12C) / N(13C) = 3:
# So F(12C) = 3/4 = 75%, F(13C) = 1/4 = 25%.
# Average atomic mass of Carbon:
# M_C = 0.75 * 12 + 0.25 * 13 = 12.25 amu.

# Oxygen isotopes: 16O and 17O.
# 80% is 16O, so 20% is 17O.
# Average atomic mass of Oxygen:
# M_O = 0.80 * 16 + 0.20 * 17 = 16.20 amu.

# Average molecular mass of CO2:
# M(CO2) = M_C + 2 * M_O = 12.25 + 2 * (16.20) = 12.25 + 32.40 = 44.65 amu!

# Options: 1) 44.75  2) 44.65  3) 44.55  4) 44.45
# Option 2 is 44.65!
print("P4-Q16: M(CO2) = 44.65 amu -> Option 2")
