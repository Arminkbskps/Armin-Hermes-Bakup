# Third alkali metal (Group 1):
# 1st: Li (Z = 3)
# 2nd: Na (Z = 11)
# 3rd: K (Potassium, Z = 19)!
# So Z_X = 19.

# The metal has three isotopes with 20, 21, 22 neutrons:
# N1 = 20 => A1 = 19 + 20 = 39 (39K).
# N2 = 21 => A2 = 19 + 21 = 40 (40K).
# N3 = 22 => A3 = 19 + 22 = 41 (41K).

# Abundances:
# Sum of abundances of two heavier isotopes (F2 + F3) = 15%.
# Since F1 + F2 + F3 = 100% => F1 = 100 - 15 = 85%!
# Ratio of abundance of lightest (F1) to heaviest (F3) = 8.5:
# F1 / F3 = 8.5 => 85 / F3 = 8.5 => F3 = 10%!
# Then F2 = 15 - 10 = 5%.
# Let's check: F1 = 85%, F2 = 5%, F3 = 10%. (Sum = 100%).

# Average number of neutrons in X:
# N_avg(X) = (20 * 85 + 21 * 5 + 22 * 10) / 100
# = (1700 + 105 + 220) / 100 = 2025 / 100 = 20.25 neutrons!

# Average atomic mass of X:
# M_X = Z + N_avg = 19 + 20.25 = 39.25 g/mol.

# Formula of oxide: X2O
# Molar mass of X2O = 2 * M_X + M_O = 2 * (39.25) + 16 = 78.5 + 16 = 94.5 g/mol!
# Mass of X2O given = 189 g.
# Moles of X2O = 189 / 94.5 = 2.0 mol! (Notice 94.5 * 2 = 189! PERFECT integer!).

# Now, how many moles of neutrons in 1 mole of X2O?
# In 1 formula unit of X2O:
# From 2 atoms of X: 2 * N_avg(X) = 2 * 20.25 = 40.5 moles of neutrons.
# From 1 atom of Oxygen (16_8 O): 16 - 8 = 8 neutrons.
# Total neutrons in 1 mole of X2O = 40.5 + 8 = 48.5 moles of neutrons!
# In 2.0 moles of X2O:
# Total moles of neutrons = 2.0 * 48.5 = 97 moles of neutrons!

# Options:
# 1) 96
# 2) 99
# 3) 97
# 4) 95
# Option 3 is 97!
print("P5-Q13: Total moles of neutrons = 97 -> Option 3")
