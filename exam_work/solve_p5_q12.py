# Terephthalic acid: C8 H6 O4
# Molar mass of C8 H6 O4 = 8*12 + 6*1 + 4*16 = 96 + 6 + 64 = 166 g/mol.
# Mass of terephthalic acid = 49.8 g.
# Moles of C8 H6 O4 = 49.8 / 166 = 0.3 mol! (166 * 0.3 = 49.8).
# In 1 mole of C8 H6 O4, there are 4 moles of O atoms.
# Moles of O atoms in this sample = 0.3 * 4 = 1.2 mol O atoms.

# Condition: Number of H atoms in acetic acid (CH3COOH) is 2 times number of O atoms in terephthalic acid:
# Moles of H atoms in CH3COOH = 2 * (moles of O in C8H6O4) = 2 * 1.2 = 2.4 mol H atoms.
# Acetic acid is CH3COOH, which has 4 H atoms per molecule.
# Moles of CH3COOH = (moles of H) / 4 = 2.4 / 4 = 0.6 mol CH3COOH.
# Molar mass of CH3COOH = 2*12 + 4*1 + 2*16 = 24 + 4 + 32 = 60 g/mol.
# Mass of CH3COOH = 0.6 * 60 = 36 g!

# Now find the difference in mass of Carbon between the two samples:
# In C8 H6 O4 (0.3 mol): moles of C = 0.3 * 8 = 2.4 mol C.
# Mass of C in C8 H6 O4 = 2.4 * 12 = 28.8 g.
# In CH3COOH (0.6 mol): moles of C = 0.6 * 2 = 1.2 mol C.
# Mass of C in CH3COOH = 1.2 * 12 = 14.4 g.
# Difference in mass of C = |28.8 - 14.4| = 14.4 g!

